create table if not exists public.hotel_api_keys (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  key_prefix text not null check (char_length(key_prefix) between 6 and 24),
  key_hash text not null unique check (char_length(key_hash)=64),
  scopes text[] not null default '{}'::text[],
  status text not null default 'active' check (status in ('active','revoked')),
  rate_limit_per_min integer not null default 60 check (rate_limit_per_min between 1 and 600),
  expires_at timestamptz,
  last_used_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);

create index if not exists hotel_api_keys_property_idx on public.hotel_api_keys(property_id, status, created_at desc);

create table if not exists public.hotel_api_request_logs (
  id bigint generated by default as identity primary key,
  property_id uuid not null references public.properties(id) on delete cascade,
  api_key_id uuid references public.hotel_api_keys(id) on delete set null,
  method text not null,
  path text not null,
  status_code integer not null,
  duration_ms integer,
  ip text,
  created_at timestamptz not null default now()
);

create index if not exists hotel_api_request_logs_property_created_idx on public.hotel_api_request_logs(property_id, created_at desc);
create index if not exists hotel_api_request_logs_key_created_idx on public.hotel_api_request_logs(api_key_id, created_at desc);

alter table public.hotel_api_keys enable row level security;
alter table public.hotel_api_request_logs enable row level security;

revoke all on table public.hotel_api_keys from anon, authenticated;
revoke all on table public.hotel_api_request_logs from anon, authenticated;
grant all on table public.hotel_api_keys to service_role;
grant all on table public.hotel_api_request_logs to service_role;
grant usage, select on sequence public.hotel_api_request_logs_id_seq to service_role;

comment on table public.hotel_api_keys is 'Hashed property-scoped API credentials for Habitación Llena public API. Plaintext secrets are never persisted.';
comment on table public.hotel_api_request_logs is 'Property-scoped request log used for API auditing and first-cut rate limiting.';
